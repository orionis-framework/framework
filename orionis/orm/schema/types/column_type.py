"""Logical column types understood by the Orionis SQL compiler."""

from __future__ import annotations
from enum import StrEnum


class ColumnType(StrEnum):
    """
    Logical column types understood by the Orionis SQL compiler.

    Each member is mapped internally to the corresponding engine type by
    the database layer; models never interact with SQL types directly.
    """

    # Generic Types
    BIG_INTEGER = "big_integer"
    """Generic Types."""
    BOOLEAN = "boolean"
    """Boolean identifier: ``boolean``."""
    DATE = "date"
    """Date identifier: ``date``."""
    DATETIME = "datetime"
    """Datetime identifier: ``datetime``."""
    DOUBLE = "double"
    """Double identifier: ``double``."""
    ENUM = "enum"
    """Enum identifier: ``enum``."""
    FLOAT = "float"
    """Float identifier: ``float``."""
    INTEGER = "integer"
    """Integer identifier: ``integer``."""
    INTERVAL = "interval"
    """Interval identifier: ``interval``."""
    LARGE_BINARY = "large_binary"
    """Large binary identifier: ``large_binary``."""
    MATCH_TYPE = "match_type"
    """Match type identifier: ``match_type``."""
    NUMERIC = "numeric"
    """Numeric identifier: ``numeric``."""
    NUMERIC_COMMON = "numeric_common"
    """Numeric common identifier: ``numeric_common``."""
    PICKLE_TYPE = "pickle_type"
    """Pickle type identifier: ``pickle_type``."""
    SCHEMA_TYPE = "schema_type"
    """Schema type identifier: ``schema_type``."""
    SMALL_INTEGER = "small_integer"
    """Small integer identifier: ``small_integer``."""
    STRING = "string"
    """String identifier: ``string``."""
    TEXT = "text"
    """Text identifier: ``text``."""
    TIME = "time"
    """Time identifier: ``time``."""
    UNICODE = "unicode"
    """Unicode identifier: ``unicode``."""
    UNICODE_TEXT = "unicode_text"
    """Unicode text identifier: ``unicode_text``."""
    UUID = "uuid"
    """Uuid identifier: ``uuid``."""

    # Specific Types
    ARRAY = "array"
    """Specific Types."""
    BIGINT = "bigint"
    """Bigint identifier: ``bigint``."""
    BINARY = "binary"
    """Binary identifier: ``binary``."""
    BLOB = "blob"
    """Blob identifier: ``blob``."""
    CHAR = "char"
    """Char identifier: ``char``."""
    CLOB = "clob"
    """Clob identifier: ``clob``."""
    DECIMAL = "decimal"
    """Decimal identifier: ``decimal``."""
    DOUBLE_PRECISION = "double_precision"
    """Double precision identifier: ``double_precision``."""
    INT = "int"
    """Int identifier: ``int``."""
    JSON = "json"
    """Json identifier: ``json``."""
    NCHAR = "nchar"
    """Nchar identifier: ``nchar``."""
    NVARCHAR = "nvarchar"
    """Nvarchar identifier: ``nvarchar``."""
    REAL = "real"
    """Real identifier: ``real``."""
    SMALLINT = "smallint"
    """Smallint identifier: ``smallint``."""
    TIMESTAMP = "timestamp"
    """Timestamp identifier: ``timestamp``."""
    VARBINARY = "varbinary"
    """Varbinary identifier: ``varbinary``."""
    VARCHAR = "varchar"
    """Varchar identifier: ``varchar``."""
